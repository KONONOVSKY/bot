def in_speak_hours(n: datetime) -> bool:
    cur = (n.hour, n.minute)
    return SPEAK_FROM <= cur < SPEAK_UNTIL


def classify_window(dt: datetime) -> str:
    minutes = dt.hour * 60 + dt.minute
    if dt.hour < 3:
        return "evening"
    if minutes < 11 * 60:
        return "morning"
    if minutes < 16 * 60 + 30:
        return "midday"
    return "evening"


