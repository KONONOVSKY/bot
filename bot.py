def missing_text(window: str, n: datetime, label: str):
    today = biz_date(n).isoformat()
    reported = set(day_entries(today, window))
    
    if len(reported) >= 16:
        return None
        
    expected = expected_stores(window, today)
    miss = sorted(expected - reported)
    if miss:
        shown = ", ".join(miss[:8])
        more = f" и ещё {len(miss) - 8}" if len(miss) > 8 else ""
        return f"{label} ещё ждём от: {shown}{more}."
    return None

async def run_slot(kind: str, fallback: bool, n: datetime) -> str:
    jokes_kind = kind == "joke" or fallback
    critical_reminder = kind in ("nudge_morning", "nudge_midday")
    if not can_speak(n, jokes=False, ignore_mute=critical_reminder):
        return "retry"

    if kind in ("nudge_morning", "nudge_midday"):
        window = "morning" if kind == "nudge_morning" else "midday"
        today = biz_date(n).isoformat()
        all_reports = day_entries(today, window)
        unidentified = [s for s in all_reports if s not in STORE_NAMES]
        
        if unidentified:
            status_text = "✅ Квота 16 отчетов закрыта, пуш отменен" if len(all_reports) >= 16 else "⚠️ Пуш отправлен в чат"
            msg = (f"📊 <b>Сводка (окно {window})</b>\n"
                   f"Собрано отчетов: {len(all_reports)}/16\n"
                   f"Статус: {status_text}\n"
                   f"Не идентифицированы как магазины ({len(unidentified)} шт): {', '.join(unidentified)}")
            try:
                await bot.send_message(ADMIN_ID, msg, parse_mode="HTML")
            except Exception as e:
                log.warning(f"Не удалось отправить сводку админу: {e}")
    
    text, html = None, False
    is_joke = False
    
    if kind == "greeting":
        text = greeting_text(n)
    elif kind == "nudge_morning":
        base = missing_text("morning", n, "☕ Утренний отчёт")
        if not base:
            return "skip"
        text = f"{base} Коллеги, не забываем 🙏"
    elif kind == "nudge_midday":
        base = missing_text("midday", n, "⏳ Обеденный отчёт")
        if not base:
            return "skip"
        text = f"{base} Коллеги, не забываем 🙏"
        
    if text is None and (kind == "joke" or fallback):
        if jokes_temporarily_paused():
            return "retry"
        text = queued_joke_for(n)
        html = False
        is_joke = True
        
    if text is None:
        return "skip"
    if jokes_kind and text and not can_speak(n, jokes=True):
        return "skip"
        
    ok = await say(text, html=html, track_deletable=jokes_kind)
    if ok and is_joke:
        mark_joke_used(text)
        STATE["queued_joke"] = None
        save_state()
    return "sent" if ok else "retry"

async def tick() -> None:
    n = now()
    if not get_chat_id():
        return

    today = n.date().isoformat()
    done = STATE["done"].setdefault(today, [])
    for old in sorted(STATE["done"])[:-3]:
        STATE["done"].pop(old, None)
    for slot_id, h, m, kind, fallback in SLOTS:
        if slot_id in done:
            continue
        start = n.replace(hour=h, minute=m, second=0, microsecond=0)
        if n < start:
            continue

        if kind == "joke":
            if n >= min(start + timedelta(minutes=JOKE_MAX_DELAY_MIN), joke_window_end(start)):
                done.append(slot_id)
                continue
            if jokes_temporarily_paused():
                continue
        elif n > start + timedelta(minutes=SLOT_GRACE_MIN):
            done.append(slot_id)
            continue

        status = await run_slot(kind, fallback, n)
        if status in ("sent", "skip"):
            mark_slot_done(done, slot_id)
            save_state()
            break  
        if status == "retry":
            continue
        break

async def scheduler_loop() -> None:
    while True:
        try:
            if not RT.is_suspended and not is_after_hard_mute():
                await tick()
        except Exception:
            log.exception("Ошибка планировщика")
        await asyncio.sleep(20)

