def missing_text(window: str, n: datetime, label: str):
    today = biz_date(n).isoformat()
    reported = set(day_entries(today, window))
    expected = expected_stores(window, today)
    miss = sorted(expected - reported)
    if miss:
        shown = ", ".join(miss[:8])
        more = f" и ещё {len(miss) - 8}" if len(miss) > 8 else ""
        return f"{label} ещё ждём от: {shown}{more}. Коллеги, не забываем 🙏"
    return None

async def run_slot(kind: str, fallback: bool, n: datetime) -> str:
    jokes_kind = kind == "joke" or fallback
    if not can_speak(n, jokes=False):
        return "retry"
    text, html = None, False
    if kind == "greeting":
        text = greeting_text(n)
    elif kind == "push":
        text = pick_bag("push", PUSH_MESSAGES)
    elif kind == "tips":
        text = pick_bag("tips", JOKES["tips"])
    elif kind == "nudge_morning":
        text = missing_text("morning", n, "☕ Утренний отчёт")
        if not text:
            return "skip"
    elif kind == "nudge_midday":
        text = missing_text("midday", n, "⏳ Обеденный отчёт")
    elif kind == "summary":
        today = biz_date(n)
        text = build_yesterday(today)
        html = text is not None
    if text is None and (kind == "joke" or fallback):
        if jokes_temporarily_paused():
            return "retry"
        text = joke_for(n)
        html = False
    if text is None:
        return "skip"
    if jokes_kind and text and not can_speak(n, jokes=True):
        return "skip"
        
    return "sent" if await say(text, html=html, track_deletable=jokes_kind) else "retry"

async def tick() -> None:
    n = now()
    if not get_chat_id():
        return
        
    today = n.date().isoformat()
    done = STATE["done"].setdefault(today, [])
    for old in sorted(STATE["done"])[:-3]:
        STATE["done"].pop(old, None)
    for slot_id, h, m, kind, fallback in SLOTS:
        if slot_id in done:
            continue
        start = n.replace(hour=h, minute=m, second=0, microsecond=0)
        if n < start:
            continue

        if kind == "joke":
            # шутка живёт не дольше JOKE_MAX_DELAY_MIN и не выходит за окно 11-13 / 15-17
            if n >= min(start + timedelta(minutes=JOKE_MAX_DELAY_MIN), joke_window_end(start)):
                done.append(slot_id)
                continue
            # пауза 30 мин после последнего сообщения руководителя (в т.ч. из загруженной истории)
            if jokes_temporarily_paused():
                continue
            if time.time() - RT.last_bot < JOKE_MIN_GAP_MIN * 60:
                continue                      
        elif n > start + timedelta(minutes=SLOT_GRACE_MIN):
            done.append(slot_id)
            continue

        status = await run_slot(kind, fallback, n)
        if status in ("sent", "skip"):
            mark_slot_done(done, slot_id)
            save_state()
            break  
        if status == "retry":
            continue
        break


async def scheduler_loop() -> None:
    while True:
        try:
            # Если бот на паузе (ожидание истории/подтверждения) - графики не срабатывают
            if not RT.is_suspended:
                await tick()
        except Exception:
            log.exception("Ошибка планировщика")
        await asyncio.sleep(20)


