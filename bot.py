async def run_slot(kind: str, fallback: bool, n: datetime) -> str:
    mode = get_bot_mode()
    if mode in ("stop", "silent"):
        return "skip"
    jokes_kind = kind == "joke" or fallback
    critical_reminder = kind in ("nudge_morning", "nudge_midday")
    if jokes_kind and mode == "no_jokes":
        return "skip"
    if not can_speak(n, jokes=False, ignore_mute=critical_reminder):
        return "retry"

    text, html = None, False
    msg_type = "text"
    track_del = False

    if kind == "greeting":
        text = greeting_text(n)

    elif kind in ("nudge_morning", "nudge_midday"):
        if RT.resumed_ts and time.time() - RT.resumed_ts < 120:
            log.info("nudge пропускаем: grace period %d сек", int(time.time() - RT.resumed_ts))
            return "retry"
        window = "morning" if kind == "nudge_morning" else "midday"
        today = biz_date(n).isoformat()
        total_count = count_reports_today(today, window)

        if total_count >= TOTAL_STORES:
            log.info("nudge_%s пропускаем: %d/%d отчётов получено", window, total_count, TOTAL_STORES)
            try:
                await bot.send_message(
                    ADMIN_ID,
                    f"📊 <b>Окно {window}:</b> {total_count}/{TOTAL_STORES} отчётов получено — напоминание не нужно ✅",
                    parse_mode="HTML"
                )
            except Exception:
                pass
            return "skip"

        reported = set(day_entries(today, window))
        miss = sorted(set(STORE_NAMES) - reported)
        if not miss:
            log.info("nudge_%s: все идентифицированные сдали (%d/%d), пропускаем", window, total_count, TOTAL_STORES)
            return "skip"

        try:
            await bot.send_message(
                ADMIN_ID,
                f"📊 <b>Окно {window}:</b> {total_count}/{TOTAL_STORES} отчётов.\n"
                f"Не идентифицированы или не сдали: {', '.join(miss[:8])}{'...' if len(miss) > 8 else ''}\n"
                f"Отправлено напоминание в группу.",
                parse_mode="HTML"
            )
        except Exception:
            pass

        label_cap = "☕ Утренний отчёт" if window == "morning" else "⏳ Обеденный отчёт"
        shown = ", ".join(miss[:8])
        more = f" и ещё {len(miss) - 8}" if len(miss) > 8 else ""
        text = f"{label_cap} ещё ждём от: {shown}{more}. Коллеги, пожалуйста, не забываем 🙏"
        msg_type = "reminder"
        track_del = True

    if text is None and jokes_kind:
        if jokes_temporarily_paused():
            return "retry"
        text = queued_joke_for(n)
        html = False
        msg_type = "joke"
        track_del = True

    if text is None:
        return "skip"

    ok = await say(text, html=html, track_deletable=track_del, msg_type=msg_type)
    if ok and msg_type == "joke":
        mark_joke_used(text)
        STATE["queued_joke"] = None
        save_state()
    return "sent" if ok else "retry"

async def tick() -> None:
    n = now()
    if not get_chat_id():
        return
    today = n.date().isoformat()
    
    # Автогенерация шуток в ЛС администратору один раз в день (в нерабочее время)
    if is_after_hard_mute() and STATE.get("last_auto_gen_date") != today:
        suggested = STATE.setdefault("suggested_jokes", {})
        joke_text = generate_auto_joke()
        s_id = secrets.token_hex(4)
        suggested[s_id] = joke_text
        STATE["last_auto_gen_date"] = today
        save_state()
        kb = InlineKeyboardMarkup(inline_keyboard=[
            [
                InlineKeyboardButton(text="✅ Добавить в банк", callback_data=f"sug:add:{s_id}"),
                InlineKeyboardButton(text="❌ Отклонить", callback_data=f"sug:del:{s_id}")
            ]
        ])
        try:
            await bot.send_message(
                ADMIN_ID, 
                f"🤖 <b>Ежедневная автогенерация шутки:</b>\n\n{escape(joke_text)}", 
                parse_mode="HTML", 
                reply_markup=kb
            )
        except Exception as e:
            log.warning("Не удалось отправить автогенерацию в ЛС: %s", e)

    done = STATE["done"].setdefault(today, [])
    for old in sorted(STATE["done"])[:-3]:
        STATE["done"].pop(old, None)

    for slot_id, h, m, kind, fallback in SLOTS:
        if slot_id in done:
            continue
        start = n.replace(hour=h, minute=m, second=0, microsecond=0)
        if n < start:
            continue

        if kind == "joke":
            window_end = joke_window_end(start)
            if n >= window_end:
                done.append(slot_id)
                continue
            if jokes_temporarily_paused():
                continue
        elif n > start + timedelta(minutes=SLOT_GRACE_MIN):
            done.append(slot_id)
            continue

        status = await run_slot(kind, fallback, n)
        if status in ("sent", "skip"):
            mark_slot_done(done, slot_id)
            save_state()
            break
        if status == "retry":
            if kind in ("nudge_morning", "nudge_midday"):
                break
            continue
        break

async def scheduler_loop() -> None:
    await asyncio.sleep(90)
    log.info("Планировщик активирован (90 сек после старта)")
    while True:
        try:
            if get_bot_mode() not in ("stop", "silent") and not RT.is_suspended and not is_after_hard_mute():
                await tick()
        except Exception:
            log.exception("Ошибка планировщика")
        await asyncio.sleep(20)

