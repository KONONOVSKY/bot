def report_reactions(window: str, pct, closed: bool) -> list:
    if window == "morning":
        return ["👍", "😎", "🤝", "🫡"]
    if closed or (pct is not None and pct >= 100):
        return ["🔥", "🎉", "🤩", "🏆", "💯"] if (pct or 100) < 200 else ["🔥", "🏆", "🤩", "💯"]
    if pct is None:
        return ["👍"]
    if window == "midday":
        if pct >= 80:
            return ["🔥", "👍", "⚡"]
        if pct >= 50:
            return ["🔥", "😎", "👏"]
        if pct >= 25:
            return ["👍", "🤝", "👌"]
        return ["👀", "🫡", "🤝"]
    if pct >= 70:
        return ["👍", "🤝", "👌", "⚡"]
    if pct >= 40:
        return ["👀", "🫡", "🤝"]
    return ["👍", "🤝"]


