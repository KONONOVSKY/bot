SLOTS = [
    # Сначала обязательные приветствие/напоминания; шутки не должны блокировать их.
    ("greet", 8, 0, "greeting", False),
    ("nudge_m", 8, 55, "nudge_morning", False),
    ("sum", 9, 30, "summary", True),
    ("tips", 10, 0, "tips", False),
    ("j11", 11, 0, "joke", False),
    ("j12", 12, 0, "joke", False),
    ("nudge_d", 13, 30, "nudge_midday", False),
    ("j15", 15, 0, "joke", False),
    ("j16", 16, 0, "joke", False),
    ("push", 17, 45, "push", False),
]


def missing_text(window: str, n: datetime, label: str):
    today = biz_date(n).isoformat()
    reported = set(day_entries(today, window))
    expected = expected_stores(window, today)
    miss = sorted(expected - reported)
    if miss:
        shown = ", ".join(miss[:8])
        more = f" и ещё {len(miss) - 8}" if len(miss) > 8 else ""
        return f"{label} ещё ждём от: {shown}{more}. Коллеги, не забываем 🙏"
    return None


async def run_slot(kind: str, fallback: bool, n: datetime) -> str:
    jokes_kind = kind == "joke" or fallback
    if not can_speak(n, jokes=False):
        return "retry"
    text, html = None, False
    if kind == "greeting":
        text = greeting_text(n)
    elif kind == "push":
        text = pick_bag("push", PUSH_MESSAGES)
    elif kind == "tips":
        text = pick_bag("tips", JOKES["tips"])
    elif kind == "nudge_morning":
        text = missing_text("morning", n, "☕ Утренний отчёт")
        if not text:
            return "skip"
    elif kind == "nudge_midday":
        text = missing_text("midday", n, "⏳ Обеденный отчёт")
    elif kind == "summary":
        today = biz_date(n)
        text = build_yesterday(today)
        html = text is not None
    if text is None and (kind == "joke" or fallback):
        if jokes_temporarily_paused():
            return "retry"
        text = joke_for(n)
        html = False
    if text is None:
        return "skip"
    if jokes_kind and text and not can_speak(n, jokes=True):
        return "skip"
        
    return "sent" if await say(text, html=html, track_deletable=jokes_kind) else "retry"


async def tick() -> None:
    n = now()
    if not get_chat_id():
        return
        
    today = n.date().isoformat()
    done = STATE["done"].setdefault(today, [])
    for old in sorted(STATE["done"])[:-3]:
        STATE["done"].pop(old, None)
    for slot_id, h, m, kind, fallback in SLOTS:
        if slot_id in done:
            continue
        start = n.replace(hour=h, minute=m, second=0, microsecond=0)
        if n < start:
            continue

        if kind == "joke":
            # Шутка идёт по графику. Если руководитель недавно писал в чат, не перебиваем:
            # публикуем через 30 минут после его сообщения (правило только для шуток).
            if n > start + timedelta(minutes=JOKE_MAX_DELAY_MIN):
                done.append(slot_id)
                continue
            ready_at = start
            if RT.last_manager_message > 0:
                manager_dt = datetime.fromtimestamp(RT.last_manager_message, TZ)
                if manager_dt.date() == n.date():
                    ready_at = max(start, manager_dt + timedelta(minutes=JOKE_AFTER_MANAGER_MIN))
            if n < ready_at:
                continue
            if time.time() - RT.last_bot < JOKE_MIN_GAP_MIN * 60:
                continue                      # если шутки сдвинулись, не выдаём их подряд
        elif n > start + timedelta(minutes=SLOT_GRACE_MIN):
            done.append(slot_id)
            continue

        status = await run_slot(kind, fallback, n)
        if status in ("sent", "skip"):
            done.append(slot_id)
            save_state()
            break  # не отправляем несколько плановых сообщений подряд за один тик
        # Если шутка/сводка ждёт отчётов или паузы, не блокируем более позднее напоминание.
        if status == "retry":
            continue
        break


async def scheduler_loop() -> None:
    while True:
        try:
            await tick()
        except Exception:
            log.exception("Ошибка планировщика")
        await asyncio.sleep(20)


