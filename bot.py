def mute_for(minutes: float) -> None:
    RT.mute_until = max(RT.mute_until, time.time() + minutes * 60)


async def process(message: Message, edited: bool) -> None:
    chat = message.chat
    if chat.type not in ("group", "supergroup"):
        return
    user = message.from_user
    if user is None or user.is_bot:
        return
    head = (message.text or "").strip().lower()
    if head.startswith("/") and not edited:
        c = head.split()[0].split("@")[0]
        if c in ("/status", "/id", "/test"):
            await diag(message, c)
            return
    if not env_chat_ids() and STATE.get("chat_id") is None:
        STATE["chat_id"] = chat.id
        save_state()
        log.info("Рабочий чат запомнен: %s", chat.id)
    if not is_allowed_chat(chat.id):
        return

    name = (user.full_name or "").strip()
    text = (message.text or message.caption or "").strip()
    low = text.lower()
    n = now()
    maybe_reset_day_counters(n)

    # Официальный аккаунт головного офиса: бот только "слушает" и всегда ставит реакции
    if is_hq(name, user.id):
        await react(message, ["👍", "🔥", "😎", "💯", "🏆", "❤", "🎉"])
        if not TEST_MODE:
            if TECH_RE.search(low):
                RT.tech_at = time.time()
                mute_for(45)
            if SERIOUS_RE.search(low):
                mute_for(180)
            return

    if not edited:
        RT.last_human = time.time()
        RT.streak = 0

    if FAREWELL_RE.search(low):
        await react(message, ["🫡", "🤗"])
        if can_speak(n, gap=False):
            await say(pick_bag("farewell", SITUATIONS["farewell"]), message)
        mute_for(30)
        return

    # Серьёзные темы — полная тишина на 3 часа
    if SERIOUS_RE.search(low):
        mute_for(180)
        return

    # Команды
    if low.startswith("/") and not edited:
        cmd = low.split()[0].split("@")[0]
        if cmd in ("/top", "/today", "/joke", "/help", "/start"):
            await handle_command(message, cmd)
        return

    # Отчёты магазинов
    if text:
        rep = parse_report(text)
        if rep:
            store = store_name(name, user.id, text)
            dt = n if TEST_MODE else (message.date.astimezone(TZ) if message.date else n)
            window = classify_window(dt)
            record_report(store, window, dt, rep)
            save_state()
            if not edited:
                await handle_report(message, store, window, rep, dt)
            return

    if edited:
        return

    # Фото-чеки: всегда ждем 2 реакции от коллег (кроме обычных чеков босса без слова "туда же")
    if message.photo:
        photo_caption = (message.caption or "").strip()
        photo_low = photo_caption.lower()
        
        if is_boss(name, user.id) and not re.search(r"туда\s*же", photo_low):
            await praise_check(message, photo_caption)
        else:
            RT.photo_watch[message.message_id] = {
                "users": set(), "done": False, "sender": user.id, "msg": message, "caption": photo_caption,
            }
            for old in list(RT.photo_watch)[:-100]:
                RT.photo_watch.pop(old, None)
        return

    if not text:
        return

    # Свет / генератор — деликатная тема, шуток нет
    if POWER_RE.search(low):
        mute_for(60)
        await react(message, ["🫡"])
        return

    # Сбои 1С / связи
    if TECH_RE.search(low):
        RT.tech_at = time.time()
        mute_for(45)
        await react(message, ["🗿", "🤡", "🙈", "🥱"])
        if time.time() - RT.last_tech_reply > 1800 and can_speak(n, gap=False):
            RT.last_tech_reply = time.time()
            await say(random.choice(TECH_REPLIES), message)
        return
    if TECH_FIXED_RE.search(low) and time.time() - RT.tech_at < 5400:
        RT.mute_until = 0.0
        await react(message, ["👍", "🙏"])
        return

    if BDAY_RE.search(low):
        await react(message, ["🎉", "🍾"])
        if time.time() - RT.last_bday > 3600 and can_speak(n, gap=False):
            RT.last_bday = time.time()
            await say("🎂 Присоединяюсь к поздравлениям! Пусть план радует так же, как этот день 🎉", message)
        return

    # Общение с ботом (зумерская ирония, если пишут лично ему)
    is_bot_reply = message.reply_to_message and message.reply_to_message.from_user.id == bot.id
    has_bot_mention = re.search(r"\b(бот|бота|боту|ботяра)\b", low)

    if (is_bot_reply or has_bot_mention) and len(text) < 200:
        if can_speak(n, gap=False):
            await say(pick_bag("bot_mention", SITUATIONS["bot_mention"]), message)
        else:
            await react(message, ["🤡", "💅", "🗿", "🥱", "👀"])
        return

    # Лёгкие социальные ситуации из реальной динамики чата
    win_re = re.compile(
        r"флагман|ультр\w*|кредит\s*\+|перв\w+\s+оплат\w+\s+частями|"
        r"красив\w+\s+чек|рекорд\w*|прогресс месяца|стажер\w*.*(удив|кредит|ультр)",
        re.IGNORECASE,
    )
    if len(text) <= 220 and win_re.search(text) and not SERIOUS_RE.search(low) and not is_boss(name, user.id):
        if can_speak(n, gap=False) and time.time() - RT.last_praise > 900 and RT.praise_n < MAX_PRAISE_PER_DAY:
            pool = [
                "😎 Вот это апгрейд смены! Красиво, коллеги 🔥",
                "📈 Такие моменты и делают рабочий чат живым. Респект команде!",
                "🫡 Зафиксировано: сегодня кто-то явно пришёл не просто постоять у витрины.",
                "🔥 Хороший результат — хороший повод порадоваться вместе. Так держать!",
                "💅 Чек с вайбом «не зря открывали смену». Красиво!",
                "🚀 Вот это уже похоже на highlight дня. Поздравляю команду!",
                "👏 Когда консультация складывается в результат — приятно всем участникам.",
                "🏆 Красиво! Пусть такие поводы для 🔥 будут почаще.",
                "😎 Командный чат одобряет этот апгрейд.",
                "🫶 Отличная работа. Поддержка коллег тоже часть сильного результата!"
            ]
            if await say(random.choice(pool), message):
                RT.praise_n += 1
                RT.last_praise = time.time()
        return

    # Приветствия — только реакция, один раз в день на человека
    if len(text) <= 60 and GREET_RE.search(low):
        key = (n.date().isoformat(), user.id)
        if key not in RT.greeted:
            RT.greeted.add(key)
            await react(message, ["👍", "😎", "🤗", "🫡"])


