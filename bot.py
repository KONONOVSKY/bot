@dp.message()
async def global_handler(message: Message):
    if message.chat.type in ("group", "supergroup"):
        if get_chat_id() != message.chat.id:
            save_chat_id(message.chat.id)
            logging.info(f"ID сохранён: {message.chat.id}")

    text = message.text
    if not text:
        return
    text_low = text.lower()

    if text_low.startswith("/top"):
        if not week_reports:
            await message.answer("🏆 Рейтинг пока пуст - присылайте отчёты!")
        else:
            await friday_weekly_leaderboard()
        return

    # Логика обработки отчетов
    report = parse_report(text)
    if report:
        percent = (report["to_fact"] / report["to_plan"] * 100) if report["to_plan"] else 0
        store = report["store_name"]

        entry = {"store": store, "percent": percent, "time": datetime.datetime.now()}
        today_reports.append(entry)
        week_reports.append(entry)

        if percent >= 100:
            emoji = random.choice(HIGH_REACTIONS)
        elif percent >= 70:
            emoji = random.choice(MID_REACTIONS)
        else:
            emoji = random.choice(LOW_REACTIONS)

        try:
            await bot.set_message_reaction(
                chat_id=message.chat.id,
                message_id=message.message_id,
                reaction=[ReactionTypeEmoji(emoji=emoji)],
            )
        except Exception as e:
            logging.warning(f"Ошибка реакции: {e}")
        return

    # Технические сбои (RU + UA)
    if any(trigger in text_low for trigger in OUTAGE_TRIGGERS):
        await message.reply(random.choice(OUTAGE_REPLIES))
        try:
            await bot.set_message_reaction(
                chat_id=message.chat.id,
                message_id=message.message_id,
                reaction=[ReactionTypeEmoji(emoji=random.choice(OUTAGE_REACTIONS))],
            )
        except Exception as e:
            logging.warning(f"Ошибка реакции на сбой: {e}")
        return
        
    # Пасхалка на отписки по посылках (RU + UA)
    if any(trigger in text_low for trigger in PARCEL_TRIGGERS):
        await message.reply(random.choice(PARCEL_REPLIES))
        try:
            await bot.set_message_reaction(
                chat_id=message.chat.id,
                message_id=message.message_id,
                reaction=[ReactionTypeEmoji(emoji=random.choice(PARCEL_REACTIONS))],
            )
        except Exception as e:
            logging.warning(f"Ошибка реакции на посылки: {e}")
        return

    # 20 новых ситуаций (RU + UA)
    handled_by_event = False
    for event in NEW_EVENTS:
        if any(trigger in text_low for trigger in event["triggers"]):
            await message.reply(random.choice(event["replies"]))
            try:
                await bot.set_message_reaction(
                    chat_id=message.chat.id,
                    message_id=message.message_id,
                    reaction=[ReactionTypeEmoji(emoji=random.choice(event["reactions"]))],
                )
            except Exception as e:
                logging.warning(f"Ошибка реакции на событие {event['name']}: {e}")
            handled_by_event = True
            break
            
    if handled_by_event:
        return

    # Приветствия (RU + UA)
    if any(trigger in text_low for trigger in GREETING_TRIGGERS):
        try:
            await bot.set_message_reaction(
                chat_id=message.chat.id,
                message_id=message.message_id,
                reaction=[ReactionTypeEmoji(emoji=random.choice(GREETING_REACTIONS))],
            )
        except Exception as e:
            logging.warning(f"Ошибка реакции на приветствие: {e}")
        return

    # Пульс чата
    global last_pulse_comment_at
    chat_pulse_buffer.append(text)
    if len(chat_pulse_buffer) >= PULSE_TRIGGER_COUNT:
        now = datetime.datetime.now()
        cooldown_ok = (
            last_pulse_comment_at is None
            or (now - last_pulse_comment_at).total_seconds() >= PULSE_COOLDOWN_MINUTES * 60
        )
        if cooldown_ok:
            await message.answer(random.choice(PULSE_COMMENTS))
            last_pulse_comment_at = now
        chat_pulse_buffer.clear()

async def hourly_random_joke_job():
    chat_id = get_chat_id()
    if chat_id:
        await bot.send_message(chat_id, random.choice(HOURLY_RANDOM_JOKES))

async def pre_deadline_reminder(window: str):
    chat_id = get_chat_id()
    if chat_id:
        await bot.send_message(chat_id, random.choice(PRE_DEADLINE_REMINDERS[window]))

async def post_deadline_summary(window_minutes_back: int):
    chat_id = get_chat_id()
    if not chat_id or not today_reports:
        return

    cutoff = datetime.datetime.now() - datetime.timedelta(minutes=window_minutes_back)
    recent = [r for r in today_reports if r["time"] >= cutoff]
    if not recent:
        return

    best = max(recent, key=lambda r: r["percent"])
    worst = min(recent, key=lambda r: r["percent"])

    text = f"📊 Сдали {len(recent)} точек.\n"
    text += f"👑 Акулы сегодня - {best['store']} ({best['percent']:.0f}%).\n"
    if worst["percent"] < 70 and worst["store"] != best["store"]:
        text += f"🤡 {worst['store']} пока в хвосте ({worst['percent']:.0f}%), поднажмите!"

    await bot.send_message(chat_id, text)

async def friday_weekly_leaderboard():
    chat_id = get_chat_id()
    if not chat_id or not week_reports:
        return

    by_store = {}
    for r in week_reports:
        by_store.setdefault(r["store"], []).append(r["percent"])

    averages = {store: sum(vals) / len(vals) for store, vals in by_store.items()}
    ranked = sorted(averages.items(), key=lambda x: x[1], reverse=True)

    lines = ["🏆 <b>Клуб миллионеров недели:</b>\n"]
    medals = ["🥇", "🥈", "🥉"]
    for i, (store, avg) in enumerate(ranked[:5]):
        medal = medals[i] if i < 3 else "▪️"
        lines.append(f"{medal} {store} - {avg:.0f}% в среднем за неделю")
    lines.append("\n<i>Новая неделя - новая гонка!</i>")

    await bot.send_message(chat_id, "\n".join(lines), parse_mode="HTML")

async def reset_daily_reports():
    today_reports.clear()

async def reset_weekly_reports():
    week_reports.clear()

def setup_scheduler():
    scheduler = AsyncIOScheduler(timezone="Europe/Kiev")
    
    # Ежечасные приколы строго с 10:00 до 18:00 по киевскому времени
    scheduler.add_job(hourly_random_joke_job, trigger="cron", hour="10-18", minute=0)

    scheduler.add_job(pre_deadline_reminder, trigger="cron", hour=7, minute=50, args=["morning"])
    scheduler.add_job(post_deadline_summary, trigger="cron", hour=8, minute=20, args=[40])

    scheduler.add_job(pre_deadline_reminder, trigger="cron", hour=12, minute=50, args=["midday"])
    scheduler.add_job(post_deadline_summary, trigger="cron", hour=13, minute=20, args=[40])

    scheduler.add_job(pre_deadline_reminder, trigger="cron", hour=17, minute=50, args=["evening"])
    scheduler.add_job(post_deadline_summary, trigger="cron", hour=19, minute=20, args=[100])

    scheduler.add_job(friday_weekly_leaderboard, trigger="cron", day_of_week="fri", hour=19, minute=30)
    scheduler.add_job(reset_daily_reports, trigger="cron", hour=0, minute=0)
    scheduler.add_job(reset_weekly_reports, trigger="cron", day_of_week="mon", hour=0, minute=1)
    scheduler.start()

async def handle_ping(request):
    return web.Response(text="OK, bot is alive")

async def start_keepalive_server():
    app = web.Application()
    app.router.add_get("/", handle_ping)
    runner = web.AppRunner(app)
    await runner.setup()
    port = int(os.environ.get("PORT", 10000))
    site = web.TCPSite(runner, "0.0.0.0", port)
    await site.start()

async def main():
    setup_scheduler()
    await bot.delete_webhook(drop_pending_updates=True)
    await start_keepalive_server()
    await dp.start_polling(bot)

if __name__ == "__main__":
    asyncio.run(main())